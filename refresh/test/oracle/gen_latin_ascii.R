# Oracle for refresh/latinAscii.ts: what ICU's Latin-ASCII transliteration does to every character in the ranges
# where it does anything. Run from the repository root: Rscript refresh/test/oracle/gen_latin_ascii.R
library(stringi)
cps <- c(0x80:0x24F, 0x1E00:0x1EFF, 0x2000:0x2122, 0x2190:0x21FF, 0x2460:0x24FF, 0xFB00:0xFB06, 0xFF01:0xFF5E)
chars <- intToUtf8(cps, multiple = TRUE)
mapped <- stri_trans_general(chars, id = "Latin-ASCII")
keep <- which(mapped != chars & grepl("^[\\x20-\\x7e]*$", mapped, perl = TRUE))
esc <- function(s) paste0("\"", gsub("([\\\\\"])", "\\\\\\1", s), "\"")
lines <- vapply(keep, function(i) sprintf("  [\"\\u{%04X}\", %s],", cps[i], esc(mapped[i])), "")
src <- c(
  "// Generated by refresh/test/oracle/gen_latin_ascii.R from ICU's Latin-ASCII transliteration (the one R's stringi uses).",
  "// Characters not listed here are left alone, as ICU leaves them.",
  "export const LATIN_ASCII: ReadonlyMap<string, string> = new Map([",
  lines,
  "]);", ""
)
writeLines(src, "refresh/latinAscii.ts")
cat("mapped", length(keep), "characters; ICU version", as.character(stri_info()$ICU.version), "\n")
